export const childIconFor = (label: string, path = ""): IconComponent =>
  CHILD_ICON_RULES.find(([pattern]) => pattern.test(label))?.[1] ??
  CHILD_ICON_RULES.find(([pattern]) => pattern.test(path))?.[1] ??
  FileIcon;
